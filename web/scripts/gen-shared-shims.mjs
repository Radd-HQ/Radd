/**
 * Generate the "shared singleton" shim modules for native-ESM federation (spec 94).
 *
 * Each remote build EXTERNALIZES the shared deps, keeping bare `import ... from "react"` specifiers.
 * The host's index.html import map maps those specifiers to these generated `/shared/*.js` files,
 * each of which re-exports the host's SINGLETON instance read from `globalThis.__RADD_SHARED__`
 * (populated by web/src/shared-runtime.ts at boot). Result: one React, one query client, one slot
 * registry across host + every remote — no module-federation plugin, just standard ES modules.
 *
 * Run: `node scripts/gen-shared-shims.mjs` (idempotent; re-run after upgrading a shared dep).
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(here, "../public/shared");

// id (the bare specifier remotes import) → slug (the /shared/<slug>.js filename).
const NPM_MODULES = [
  ["react", "react"],
  ["react/jsx-runtime", "react-jsx-runtime"],
  ["react/jsx-dev-runtime", "react-jsx-dev-runtime"],
  ["react-dom", "react-dom"],
  ["react-dom/client", "react-dom-client"],
  ["@tanstack/react-query", "tanstack-react-query"],
  ["@tanstack/react-router", "tanstack-react-router"],
];

// The SDK is TypeScript (no runtime introspection), so its export list is maintained here to match
// web/packages/plugin-sdk/src/index.ts. A drift shows up as an undefined import at runtime.
const SDK_EXPORTS = [
  "UI_API_VERSION", "isUiApiCompatible",
  "SlotId", "Slot", "useSlot", "useSlotMatch", "registerSlot", "unregisterSlot",
  "unregisterPlugin", "activeSlotPlugins", "useActiveSlotPlugins", "useDisabledNavPaths",
  "useDisabledMatches",
  "syncContributionPrefs", "setUserContributionEnabled", "setGlobalContributionEnabled",
  "useUserContributionToggles", "useGlobalContributionToggles",
  "UserContributionToggles", "GlobalContributionToggles",
  "definePlugin",
  "Button", "TextField", "TextArea", "Select", "Chip", "Card", "Spinner", "EmptyState", "Modal",
  "Avatar",
  "tokens",
  "api", "ApiError", "API_BASE",
  "useCurrentUser", "usePermissions", "useCapabilities", "useHasPlugin",
  "useItemsQuery", "useItemQuery", "useProjectsQuery", "useApiQueryClient",
];

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function emit(id, names, hasDefault) {
  const valid = names.filter((n) => n !== "default" && IDENT.test(n));
  const lines = [
    `// AUTO-GENERATED by scripts/gen-shared-shims.mjs — do not edit.`,
    `// Re-exports the host singleton for "${id}" from the shared federation scope.`,
    `const M = globalThis.__RADD_SHARED__ && globalThis.__RADD_SHARED__[${JSON.stringify(id)}];`,
    `if (!M) throw new Error("radd federation: shared module ${id} not registered by host");`,
    ...valid.map((n) => `export const ${n} = M[${JSON.stringify(n)}];`),
  ];
  if (hasDefault) lines.push(`export default M["default"] !== undefined ? M["default"] : M;`);
  return lines.join("\n") + "\n";
}

mkdirSync(outDir, { recursive: true });

for (const [id, slug] of NPM_MODULES) {
  const mod = await import(id);
  const names = Object.keys(mod);
  const hasDefault = "default" in mod;
  writeFileSync(resolve(outDir, `${slug}.js`), emit(id, names, hasDefault));
  console.log(`  ${id} -> shared/${slug}.js (${names.length} exports)`);
}

writeFileSync(resolve(outDir, "radd-plugin-sdk.js"), emit("@radd/plugin-sdk", SDK_EXPORTS, false));
console.log(`  @radd/plugin-sdk -> shared/radd-plugin-sdk.js (${SDK_EXPORTS.length} exports)`);
console.log("shared shims generated in", outDir);
