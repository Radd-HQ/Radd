/**
 * Plugin UI packages: discovery, workspace links, and the static-plugin list (RADD-1373).
 *
 * A plugin's UI lives IN the plugin (`<module>/ui/`). Two kinds:
 *   - BUNDLED (`"radd": {"bundled": true}` in its package.json): a core plugin, which cannot be
 *     disabled. The host imports its entry at build time and registers it at boot — no remote, no
 *     load gap. `web/src/plugins/static.generated.ts` lists them.
 *   - REMOTE (a `vite.config.mjs`): an optional plugin, built to `ui/dist/remoteEntry.js` and
 *     loaded at runtime when enabled.
 * A package with `exports` is also a public contract other packages (and the host) may import by
 * name; every such package is linked into web/node_modules.
 */
import { existsSync, lstatSync, mkdirSync, readdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const webRoot = resolve(here, "..");
export const repoRoot = resolve(webRoot, "..");
const sharedNodeModules = resolve(webRoot, "node_modules");
export const STATIC_LIST = resolve(webRoot, "src/plugins/static.generated.ts");

/** Directories to scan for plugin `ui/` packages: the builtin modules + the examples. */
const SCAN_ROOTS = [resolve(repoRoot, "server/src/radd/modules"), resolve(repoRoot, "examples")];

function findUiDirs(root, depth = 0) {
  if (!existsSync(root) || depth > 4) return [];
  const out = [];
  for (const e of readdirSync(root, { withFileTypes: true })) {
    if (!e.isDirectory() || e.name === "node_modules" || e.name === "dist") continue;
    const child = resolve(root, e.name);
    if (e.name === "ui" && existsSync(resolve(child, "package.json"))) out.push(child);
    else out.push(...findUiDirs(child, depth + 1));
  }
  return out;
}

/** Every plugin UI package, sorted by directory. */
export function discover() {
  return SCAN_ROOTS.flatMap((root) => findUiDirs(root)).sort().map((dir) => {
    const pkg = JSON.parse(readFileSync(resolve(dir, "package.json"), "utf8"));
    return {
      dir,
      pkg,
      plugin: pkg.name?.replace(/^@radd-plugin-ui\//, ""),
      bundled: pkg.radd?.bundled === true,
      remote: existsSync(resolve(dir, "vite.config.mjs")),
    };
  });
}

function link(path, target) {
  const existing = lstatSync(path, { throwIfNoEntry: false });
  if (existing && !existing.isSymbolicLink()) throw new Error(`Refusing to overwrite: ${path}`);
  if (existing) rmSync(path);
  mkdirSync(dirname(path), { recursive: true });
  symlinkSync(target, path, "dir");
}

/** Link each package's node_modules to the shared toolchain, and each public package by name. */
export function linkPackages(packages) {
  const names = new Set();
  for (const { dir, pkg, bundled, remote } of packages) {
    link(resolve(dir, "node_modules"), sharedNodeModules);
    if (bundled && remote) throw new Error(`${pkg.name} is bundled and cannot also build a remote`);
    if (!pkg.exports) continue;
    if (!/^@radd-plugin-ui\/[a-z0-9-]+$/.test(pkg.name)) throw new Error(`Invalid public package: ${pkg.name}`);
    if (names.has(pkg.name)) throw new Error(`Duplicate public package: ${pkg.name}`);
    if (bundled && pkg.exports["."] === undefined) throw new Error(`${pkg.name} is bundled but exports no entry`);
    names.add(pkg.name);
    link(resolve(sharedNodeModules, pkg.name), dir);
  }
  return names;
}

/** The generated module the host imports: every bundled plugin's entry, by plugin name. */
export function staticListSource(packages) {
  const bundled = packages.filter((p) => p.bundled);
  const ident = (plugin) => plugin.replace(/[^a-zA-Z0-9]/g, "_");
  return [
    "// GENERATED by web/scripts/plugin-packages.mjs (RADD-1373) — do not edit.",
    "// Core plugins' UI, bundled with the host and registered at boot. Optional plugins are",
    "// remotes, loaded at runtime when enabled.",
    'import type { PluginModule } from "@radd/plugin-sdk";',
    ...bundled.map((p) => `import ${ident(p.plugin)} from "${p.pkg.name}";`),
    "",
    "export const STATIC_PLUGINS: Record<string, PluginModule> = {",
    ...bundled.map((p) => `  ${JSON.stringify(p.plugin)}: ${ident(p.plugin)},`),
    "};",
    "",
  ].join("\n");
}

export function writeStaticList(packages) {
  mkdirSync(dirname(STATIC_LIST), { recursive: true });
  writeFileSync(STATIC_LIST, staticListSource(packages));
}
